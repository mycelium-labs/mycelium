class _LazyModule(_ModuleType):
    def __getattribute__(self, name: str):
        # Importing a submodule automatically places it on the package.  If
        # its basename is also a historical root export (for example
        # ``task_ledger``), resolve the export instead of leaking that module.
        lazy_imports = _ModuleType.__getattribute__(self, "__dict__").get("_LAZY_IMPORTS", {})
        if name in lazy_imports:
            value = _ModuleType.__getattribute__(self, "__dict__").get(name)
            if isinstance(value, _ModuleType) or value is None:
                return self.__getattr__(name)
        return _ModuleType.__getattribute__(self, name)


def __getattr__(name: str):
    """Load a documented root export or historical submodule on demand."""
    if name in _PUBLIC_SUBMODULES:
        value = _import_module(f"{__name__}.{name}")
        globals()[name] = value
        return value
    try:
        module_name, attribute_name = _LAZY_IMPORTS[name]
    except KeyError as exc:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}") from exc
    value = getattr(_import_module(module_name), attribute_name)
    globals()[name] = value
    return value


